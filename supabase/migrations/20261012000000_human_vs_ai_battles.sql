-- Human vs. AI caption battles, the daily caption challenge, the "My Posts"
-- dashboard, AI-generated photos, editing/deleting your own content, and the
-- guest "Human or AI?" guessing game.
--
-- Run this once in the Supabase SQL Editor (or via `supabase db push`),
-- after 20261005000000_captions_votes_rls.sql. Safe to re-run. Existing
-- photos, captions, and votes are kept: every existing caption is marked as
-- written by AI, and every existing photo is assigned to the challenge day
-- it was posted on.
--
-- Backwards compatible with the Assignment #4 app: every new column has a
-- default, so the currently deployed code keeps working (posting, voting,
-- feed) until the new code is deployed.

begin;

-- ---------------------------------------------------------------------------
-- Schema
-- ---------------------------------------------------------------------------

-- Who wrote each caption. Existing rows were all written by Gemini. The
-- 'ai' default keeps the previously deployed code (which doesn't send
-- author_type) working. It can't be abused to disguise a human caption: the
-- table only accepts AI captions from the photo's owner right after posting,
-- and human captions only come in through submit_human_caption().
alter table public.captions
  add column if not exists author_type text not null default 'ai'
  check (author_type in ('ai', 'human'));
alter table public.captions alter column author_type set default 'ai';

-- Human captions are kept shorter than the 300-character AI limit.
alter table public.captions drop constraint if exists captions_human_text_length;
alter table public.captions
  add constraint captions_human_text_length
  check (author_type = 'ai' or char_length(text) <= 200);

create index if not exists captions_user_id_idx
  on public.captions (user_id, created_at desc);

-- The New York calendar day a photo was posted on. The daily prompt rotates
-- at midnight New York time, so this is what groups photos into a day's
-- challenge.
alter table public.generations add column if not exists challenge_date date;
update public.generations
  set challenge_date = (created_at at time zone 'America/New_York')::date
  where challenge_date is null;
alter table public.generations
  alter column challenge_date set default ((now() at time zone 'America/New_York')::date);
alter table public.generations alter column challenge_date set not null;

create index if not exists generations_challenge_date_idx
  on public.generations (challenge_date);

-- Whether the photo was uploaded or generated by AI, and the prompt used to
-- generate it.
alter table public.generations
  add column if not exists image_source text not null default 'upload'
  check (image_source in ('upload', 'ai'));
alter table public.generations
  add column if not exists image_prompt text
  check (char_length(image_prompt) <= 300);

-- ---------------------------------------------------------------------------
-- Keep authorship secret
-- ---------------------------------------------------------------------------

-- The whole game is guessing whether a caption was written by a person or by
-- Gemini, so the API must not hand that out. author_type and user_id give it
-- away directly, and created_at does indirectly (AI captions are written the
-- second the photo is posted). Everyone can still read the text and the vote
-- totals. Authorship is revealed only through caption_reveals() below.
revoke select on public.captions from anon, authenticated;
grant select (id, generation_id, text, upvotes, downvotes, score)
  on public.captions to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Functions
-- ---------------------------------------------------------------------------
-- These are security definer so they can read the hidden columns, and each
-- one decides for itself what the caller is allowed to see.

-- True when the signed-in user wrote this caption by hand. Used by the vote
-- policies so nobody can upvote their own caption.
create or replace function public.is_own_human_caption(p_caption_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.captions
    where id = p_caption_id
      and user_id = auth.uid()
      and author_type = 'human'
  );
$$;

-- Who wrote each of the given captions, but only for captions the caller has
-- voted on, wrote, or that are on the caller's own photo. Signed-out callers
-- get nothing. Human authors are shown as first name + last initial.
create or replace function public.caption_reveals(p_caption_ids uuid[])
returns table (
  caption_id uuid,
  author_type text,
  author_name text,
  is_mine boolean
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id,
    c.author_type,
    case
      when c.author_type = 'human' then nullif(
        btrim(concat_ws(' ', p.first_name, left(p.last_name, 1) || '.')),
        ''
      )
    end,
    c.author_type = 'human' and c.user_id = auth.uid()
  from public.captions c
  join public.generations g on g.id = c.generation_id
  left join public.profiles p on p.id = c.user_id
  where c.id = any (p_caption_ids)
    and auth.uid() is not null
    and (
      c.user_id = auth.uid()
      or g.user_id = auth.uid()
      or exists (
        select 1 from public.caption_votes v
        where v.caption_id = c.id and v.user_id = auth.uid()
      )
    );
$$;

-- Adds a human-written caption to any photo. This is the only way to insert
-- a human caption (there is no table policy for it), so the limits here
-- can't be skipped by calling the REST API directly.
create or replace function public.submit_human_caption(
  p_generation_id uuid,
  p_text text
)
returns uuid
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_text text := btrim(regexp_replace(coalesce(p_text, ''), '\s+', ' ', 'g'));
  v_id uuid;
begin
  if v_user is null then
    raise exception 'not_signed_in' using errcode = '42501';
  end if;

  if char_length(v_text) < 1 or char_length(v_text) > 200 then
    raise exception 'invalid_length' using errcode = '22023';
  end if;

  if not exists (select 1 from public.generations where id = p_generation_id) then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  if (
    select count(*) from public.captions
    where generation_id = p_generation_id
      and user_id = v_user
      and author_type = 'human'
  ) >= 3 then
    raise exception 'post_limit' using errcode = '23514';
  end if;

  if (
    select count(*) from public.captions
    where user_id = v_user
      and author_type = 'human'
      and created_at > now() - interval '24 hours'
  ) >= 30 then
    raise exception 'daily_limit' using errcode = '23514';
  end if;

  if exists (
    select 1 from public.captions
    where generation_id = p_generation_id
      and lower(text) = lower(v_text)
  ) then
    raise exception 'duplicate' using errcode = '23505';
  end if;

  insert into public.captions (generation_id, user_id, author_type, text)
  values (p_generation_id, v_user, 'human', v_text)
  returning id into v_id;

  return v_id;
end;
$$;

-- The highest-scoring caption on photos from a finished challenge day, with
-- its author revealed. Today's winner is never revealed while voting is
-- still open.
create or replace function public.daily_winner(p_day date)
returns table (
  caption_id uuid,
  text text,
  score integer,
  author_type text,
  author_name text,
  generation_id uuid,
  image_path text,
  daily_prompt text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id,
    c.text,
    c.score,
    c.author_type,
    case
      when c.author_type = 'human' then nullif(
        btrim(concat_ws(' ', p.first_name, left(p.last_name, 1) || '.')),
        ''
      )
    end,
    g.id,
    g.image_path,
    g.daily_prompt
  from public.captions c
  join public.generations g on g.id = c.generation_id
  left join public.profiles p on p.id = c.user_id
  where g.challenge_date = p_day
    and p_day < (now() at time zone 'America/New_York')::date
    and c.score > 0
  order by c.score desc, c.upvotes desc, c.created_at asc
  limit 1;
$$;

-- Humans vs. Gemini, all time. A "battle" is a photo with at least one
-- human caption; whichever side has the single highest-scoring caption on
-- that photo wins it. Only totals come out, never which caption is which.
create or replace function public.battle_scoreboard()
returns table (human_wins integer, ai_wins integer, battles integer)
language sql
stable
security definer
set search_path = public
as $$
  with per_photo as (
    select
      generation_id,
      max(score) filter (where author_type = 'human') as best_human,
      max(score) filter (where author_type = 'ai') as best_ai
    from public.captions
    group by generation_id
    having count(*) filter (where author_type = 'human') > 0
  )
  select
    (count(*) filter (
      where best_human > 0 and best_human > coalesce(best_ai, 0)
    ))::integer,
    (count(*) filter (
      where best_ai > 0 and best_ai > best_human
    ))::integer,
    count(*)::integer
  from per_photo;
$$;

-- The signed-in user's own human captions for the dashboard, with where
-- each one ranks on its photo.
create or replace function public.my_captions()
returns table (
  caption_id uuid,
  generation_id uuid,
  text text,
  upvotes integer,
  downvotes integer,
  score integer,
  created_at timestamptz,
  image_path text,
  rank integer,
  total integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    ranked.id,
    ranked.generation_id,
    ranked.text,
    ranked.upvotes,
    ranked.downvotes,
    ranked.score,
    ranked.created_at,
    ranked.image_path,
    ranked.rank,
    ranked.total
  from (
    select
      c.id,
      c.generation_id,
      c.text,
      c.upvotes,
      c.downvotes,
      c.score,
      c.created_at,
      c.user_id,
      c.author_type,
      g.image_path,
      (rank() over (partition by c.generation_id order by c.score desc))::integer as rank,
      (count(*) over (partition by c.generation_id))::integer as total
    from public.captions c
    join public.generations g on g.id = c.generation_id
    where c.generation_id in (
      select mine.generation_id from public.captions mine
      where mine.user_id = auth.uid() and mine.author_type = 'human'
    )
  ) ranked
  where ranked.user_id = auth.uid() and ranked.author_type = 'human'
  order by ranked.created_at desc;
$$;

-- Edits the text of your own human caption. Only allowed before anyone has
-- voted on it, so nobody can swap in a different joke after it's been judged.
create or replace function public.edit_human_caption(
  p_caption_id uuid,
  p_text text
)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_text text := btrim(regexp_replace(coalesce(p_text, ''), '\s+', ' ', 'g'));
  v_caption public.captions%rowtype;
begin
  if v_user is null then
    raise exception 'not_signed_in' using errcode = '42501';
  end if;

  select * into v_caption from public.captions
  where id = p_caption_id and user_id = v_user and author_type = 'human'
  for update;

  if not found then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  if v_caption.upvotes + v_caption.downvotes > 0 then
    raise exception 'has_votes' using errcode = '23514';
  end if;

  if char_length(v_text) < 1 or char_length(v_text) > 200 then
    raise exception 'invalid_length' using errcode = '22023';
  end if;

  if exists (
    select 1 from public.captions
    where generation_id = v_caption.generation_id
      and id <> p_caption_id
      and lower(text) = lower(v_text)
  ) then
    raise exception 'duplicate' using errcode = '23505';
  end if;

  update public.captions set text = v_text where id = p_caption_id;
end;
$$;

-- Deletes your own human caption (and the votes on it).
create or replace function public.delete_human_caption(p_caption_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'not_signed_in' using errcode = '42501';
  end if;

  delete from public.captions
  where id = p_caption_id
    and user_id = auth.uid()
    and author_type = 'human';

  if not found then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
end;
$$;

-- The guest guessing game: a random caption from a finished challenge day
-- (never today's, whose authors are still secret), with roughly even odds of
-- it being human or AI when both exist. Doesn't say who wrote it.
create or replace function public.guess_round(p_exclude uuid[] default '{}')
returns table (
  caption_id uuid,
  text text,
  image_path text,
  generation_id uuid
)
language sql
volatile
security definer
set search_path = public
as $$
  select c.id, c.text, g.image_path, g.id
  from public.captions c
  join public.generations g on g.id = c.generation_id
  where g.challenge_date < (now() at time zone 'America/New_York')::date
    and not (c.id = any (coalesce(p_exclude, '{}')))
  order by
    c.author_type = (
      select case when random() < 0.5 then 'human' else 'ai' end
    ) desc,
    random()
  limit 1;
$$;

-- Checks a guess from the guessing game and reveals the author. Like
-- guess_round(), only works for captions from finished challenge days.
create or replace function public.check_guess(
  p_caption_id uuid,
  p_guess text
)
returns table (
  correct boolean,
  author_type text,
  author_name text,
  score integer,
  generation_id uuid
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.author_type = p_guess,
    c.author_type,
    case
      when c.author_type = 'human' then nullif(
        btrim(concat_ws(' ', p.first_name, left(p.last_name, 1) || '.')),
        ''
      )
    end,
    c.score,
    g.id
  from public.captions c
  join public.generations g on g.id = c.generation_id
  left join public.profiles p on p.id = c.user_id
  where c.id = p_caption_id
    and g.challenge_date < (now() at time zone 'America/New_York')::date;
$$;

