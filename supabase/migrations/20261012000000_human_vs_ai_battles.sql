-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------

alter table public.generations enable row level security;
alter table public.captions enable row level security;
alter table public.caption_votes enable row level security;

-- generations: you can only post as yourself, and only into today's
-- challenge (so nobody can backdate a photo into yesterday's contest).
drop policy if exists "Users can create their own generations" on public.generations;
create policy "Users can create their own generations"
  on public.generations for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and challenge_date = (now() at time zone 'America/New_York')::date
  );

-- generations: owners can edit the context line on their post (no other
-- column, enforced by the column grant) and delete their post, which also
-- deletes its captions and votes.
revoke update on public.generations from anon, authenticated;
grant update (context) on public.generations to authenticated;

drop policy if exists "Users can edit their own generations" on public.generations;
create policy "Users can edit their own generations"
  on public.generations for update
  to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "Users can delete their own generations" on public.generations;
create policy "Users can delete their own generations"
  on public.generations for delete
  to authenticated
  using (user_id = auth.uid());

-- captions: the table policy now only covers Gemini's captions, written by
-- the server right after the photo is posted. Human captions go through
-- submit_human_caption().
drop policy if exists "Users can add captions to their own generations" on public.captions;
drop policy if exists "Owners can add AI captions to their new generations" on public.captions;
create policy "Owners can add AI captions to their new generations"
  on public.captions for insert
  to authenticated
  with check (
    author_type = 'ai'
    and user_id = auth.uid()
    and exists (
      select 1 from public.generations g
      where g.id = generation_id
        and g.user_id = auth.uid()
        and g.created_at > now() - interval '10 minutes'
    )
  );

-- caption_votes: same as before, plus no voting on your own human caption.
drop policy if exists "Users can cast their own votes" on public.caption_votes;
create policy "Users can cast their own votes"
  on public.caption_votes for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and not public.is_own_human_caption(caption_id)
  );

drop policy if exists "Users can change their own votes" on public.caption_votes;
create policy "Users can change their own votes"
  on public.caption_votes for update
  to authenticated
  using (user_id = auth.uid())
  with check (
    user_id = auth.uid()
    and not public.is_own_human_caption(caption_id)
  );

-- Tell the API to pick up the new columns, grants, and functions.
notify pgrst, 'reload schema';

commit;
